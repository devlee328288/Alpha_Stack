"""총수익 축이 배당을 제대로 얹나 — 그리고 얹지 말아야 할 것을 안 얹나.

이 시험이 지키는 것은 네 가지다.

  1. 배당이 없으면 총수익이 가격과 **똑같이** 간다. 갈라지면 계산이 새는 것이다.
  2. 배당이 있으면 그만큼, **정확히 그만큼** 더 간다.
  3. 분할이 있던 종목에서 배당이 가격과 **같은 배율**을 탄다.
  4. 원본이 자기 정합적인지로 단위 오류를 가른다 — **크기로 자르지 않는다.**

4번이 특히 중요하다. 배당이 종가보다 큰 행 넷 중 셋이 유전펀드·리츠의 정당한
청산분배금이었다. 크기로 자르면 그 셋이 함께 잘려 총수익이 아래로 편향된다.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import pytest  # noqa: E402

from supply import total_return as TR  # noqa: E402

# ── 배당 금액 고르기 ──────────────────────────────────────────────────────────

def test_일반배당이_있으면_그것을_쓴다():
    assert TR.dividend_amount(1000.0, 600.0) == 1000.0


def test_일반배당이_비면_차등배당으로_받친다():
    """실제로 있는 자리다 — `genr=0` 인데 `grdn>0` 인 행이 7건 있다."""
    assert TR.dividend_amount(0.0, 30.0) == 30.0
    assert TR.dividend_amount(None, 30.0) == 30.0


def test_둘_다_없으면_0():
    assert TR.dividend_amount(0.0, 0.0) == 0.0
    assert TR.dividend_amount(None, None) == 0.0


# ── 액면가 되짚기 ────────────────────────────────────────────────────────────

@pytest.mark.parametrize("금액,배당률,기대", [
    (2500.0, 50.0, 5000.0),      # 현대차 — 액면 5,000 의 50%
    (375.0, 7.5, 5000.0),        # SK하이닉스
    (200.0, 4.0, 5000.0),        # 코오롱글로벌
    (600.0, 60.0, 1000.0),       # 동원산업
])
def test_배당률로_그날의_액면가를_되짚는다(금액, 배당률, 기대):
    """`genr_cash_dvdn_rt` 는 시가배당률이 아니라 **액면가 대비** 배당률이다."""
    assert TR.implied_par_price(금액, 배당률) == pytest.approx(기대)


def test_배당률이_없으면_되짚지_못한다():
    assert TR.implied_par_price(1000.0, 0.0) is None
    assert TR.implied_par_price(1000.0, None) is None


def test_되짚은_액면가가_표준값에_붙으면_성한_것으로_본다():
    assert TR.is_par_consistent(2500.0, 50.0) is True


def test_되짚은_값이_적재_액면가에_붙어도_성한_것으로_본다():
    """넥스콘테크놀러지는 액면가가 30만원이다 — 표준값 목록에 없어도 원본과 맞는다."""
    assert TR.is_par_consistent(258130.0, 86.0433333333, 300000.0) is True


def test_되짚을_수_없으면_판정하지_않는다():
    """`None` 은 "아니다" 가 아니라 "모른다" 다. 둘을 섞으면 정상 행을 버린다."""
    assert TR.is_par_consistent(3244.52, 0.0) is None


# ── 단위 오류 판정 — 크기로 자르지 않는다 ────────────────────────────────────

def test_윙입푸드_단위오류를_잡는다():
    """주당 18.5억 · 배당률도 액면가도 0 이라 되짚을 수 없고, 배당이 종가의 132만 배다."""
    assert TR.is_suspect(1851481913.0, 0.0, 1395, 0.0) is True


@pytest.mark.parametrize("이름,금액,배당률,종가,적재액면", [
    # 🔴 셋 다 배당이 종가보다 크지만 **정당한 청산분배금**이다. 크기로 자르면
    #    함께 잘려 총수익이 아래로 편향된다.
    ("코람코더원 리츠 분배 381%", 8900.0, 1780.0, 2335, 500.0),
    ("한국투자ANKOR 유전펀드 청산 5,964%", 1670.0, 56.2100302928, 28, 0.0),
    ("한국투자패러랠 유전펀드 279%", 1342.0, 52.1367521368, 481, 0.0),
])
def test_배당이_종가보다_커도_원본이_맞으면_의심하지_않는다(이름, 금액, 배당률, 종가, 적재액면):
    assert TR.is_suspect(금액, 배당률, 종가, 적재액면) is False, 이름


def test_배당률이_없어도_종가를_안_넘으면_의심하지_않는다():
    """KDR·외국기업은 액면 배당률이 없다 — 32행이 전부 정상이었다."""
    assert TR.is_suspect(3244.52, 0.0, 16600, 0.0) is False


def test_배당이_없으면_의심하지_않는다():
    assert TR.is_suspect(0.0, 0.0, 1000, 0.0) is False


# ── 총수익 누적 ──────────────────────────────────────────────────────────────

def test_배당이_없으면_총수익이_가격과_똑같이_간다():
    rows = [("20240102", 1000, 1000.0),
            ("20240103", 1100, 1100.0),
            ("20240104", 990, 990.0)]
    결과 = list(TR.total_return_series(rows, {}))
    assert [r[2] for r in 결과] == pytest.approx([1000.0, 1100.0, 990.0])
    assert all(r[1] is None for r in 결과)          # 배당 칸은 비어 있다


def test_배당이_있으면_정확히_그만큼_더_간다():
    rows = [("20240102", 1000, 1000.0),
            ("20240103", 1000, 1000.0)]            # 가격은 그대로
    배당 = {"20240103": {"amount": 50.0, "cash_rate": 5.0, "par_at_load": 1000.0}}
    결과 = list(TR.total_return_series(rows, 배당))
    # 가격이 안 움직였으므로 총수익은 배당수익률 5% 만큼만 는다.
    assert 결과[1][2] == pytest.approx(1050.0)
    assert 결과[1][1] == pytest.approx(50.0)


def test_분할이_있으면_배당도_같은_배율을_탄다():
    """수정종가가 원종가의 1/10 이면 배당도 1/10 이어야 축이 맞는다."""
    rows = [("20240102", 10000, 1000.0),
            ("20240103", 10000, 1000.0)]
    배당 = {"20240103": {"amount": 500.0, "cash_rate": 10.0, "par_at_load": 5000.0}}
    결과 = list(TR.total_return_series(rows, 배당))
    assert 결과[1][1] == pytest.approx(50.0)        # 500 × (1000/10000)
    assert 결과[1][2] == pytest.approx(1050.0)


def test_단위_오류_배당은_얹지_않고_깃발만_세운다():
    rows = [("20240102", 1395, 1395.0),
            ("20240103", 1395, 1395.0)]
    배당 = {"20240103": {"amount": 1851481913.0, "cash_rate": 0.0, "par_at_load": 0.0}}
    결과 = list(TR.total_return_series(rows, 배당))
    assert 결과[1][1] is None                       # 배당을 안 얹었다
    assert 결과[1][3] == 1                          # 그러나 표시는 남겼다
    assert 결과[1][2] == pytest.approx(1395.0)      # 총수익이 튀지 않았다


def test_수정종가가_없는_날은_비우되_누적을_끊지_않는다():
    """수정주가를 아직 안 채운 최근 며칠이 이 자리다. 끊으면 뒤가 통째로 사라진다."""
    rows = [("20240102", 1000, 1000.0),
            ("20240103", 1100, None),               # 아직 안 채운 날
            ("20240104", 1200, 1200.0)]
    결과 = list(TR.total_return_series(rows, {}))
    assert 결과[1][2] is None
    assert 결과[2][2] == pytest.approx(1200.0)      # 직전 유효일에서 이어받았다


def test_총수익은_가격_아래로_내려가지_않는다():
    """배당은 더하기만 하므로 비가 1 밑으로 갈 수 없다 — 원장이 붉게 보는 조건이다."""
    rows = [("20240102", 1000, 1000.0),
            ("20240103", 900, 900.0),
            ("20240104", 800, 800.0)]
    배당 = {"20240103": {"amount": 10.0, "cash_rate": 1.0, "par_at_load": 1000.0}}
    결과 = list(TR.total_return_series(rows, 배당))
    for (_, _, tr, _), (_, _, adj) in zip(결과, rows, strict=True):
        if tr is not None and adj:
            assert tr >= adj * (1 - 1e-9)


# ── 배당 불러오기 ────────────────────────────────────────────────────────────

def test_현금배당과_동시배당만_담는다():
    """주식배당은 수정주가가 이미 폈다 — 또 더하면 두 번 센다."""
    assert set(TR.CASH_DIVIDEND_KINDS) == {"현금배당", "동시배당"}


def test_종목별로_나눈다():
    표 = {("005930", "20240102"): {"amount": 100.0},
          ("005930", "20240402"): {"amount": 200.0},
          ("000660", "20240102"): {"amount": 50.0}}
    나눔 = TR.dividends_by_code(표)
    assert set(나눔) == {"005930", "000660"}
    assert set(나눔["005930"]) == {"20240102", "20240402"}
    assert TR.codes_with_dividends(표) == ["000660", "005930"]
