def _block_texts(b: Block) -> List[str]:
    """블록 안의 사람이 읽는 글을 모두 꺼낸다 — 본문 번호 검사용."""
    kind = b[0]
    if kind in ("h1", "h2", "h3", "p", "small"):
        return [b[1]]
    if kind in ("bullets", "code"):
        return list(b[1])
    if kind == "quote":
        return [b[1], b[2]]
    if kind == "table":
        return [cell for row in b[1] for cell in row] + [b[4]]
    if kind == "figure":
        return [b[2]]
    return []


def doc_id_leaks(blocks: Sequence[Block]) -> List[str]:
    """부록 B 앞 본문에 남은 결정 기록 · 이슈 · PR 번호를 앞뒤 글자와 함께 돌려준다."""
    leaks: List[str] = []
    for b in blocks:
        if b[0] == "h1" and b[1].startswith("부록 B"):
            break
        for text in _block_texts(b):
            for m in DOC_ID_PATTERN.finditer(text):
                leaks.append("…" + text[max(0, m.start() - 24):m.end() + 16] + "…")
    return leaks


def report_blocks() -> List[Block]:
    """본문 전체. 장을 더할 때 여기에 잇는다."""
    return (front_blocks() + ch1_blocks() + ch2_blocks() + ch3_blocks()
            + ch4_blocks() + ch5_blocks() + ch6_blocks() + ch7_blocks()
            + ch8_blocks() + ch9_blocks() + ch10_blocks() + appendix_blocks())


