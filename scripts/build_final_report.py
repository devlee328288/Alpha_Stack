    ap.add_argument("--pdf", type=Path, default=None,
                    help="--word 와 함께 — 확인용 PDF 를 이 경로에 뽑는다")
    args = ap.parse_args()

    if not args.base.exists():
        print("🔴 스타일 기반 파일이 없습니다: " + str(args.base))
        print("   계획서 v1.0 docx 가 있어야 한글 글꼴을 물려받습니다.")
        return 1

    blocks = _number(report_blocks())
    doc = Document(str(args.base))
    plan._clear_body(doc)
    _cover(doc)
    build_docx(doc, blocks)
    _page_numbers(doc)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(args.out))
    n_fig = sum(1 for b in blocks if b[0] == "figure")
    print("✅ " + str(args.out))
    print(f"   표 {len(doc.tables)}개 · 그림 {n_fig}개 · 문단 {len(doc.paragraphs)}개")

    out_html = args.out.with_suffix(".html")
    page = render_html(blocks, out_html)
    out_html.write_text(page, encoding="utf-8")
