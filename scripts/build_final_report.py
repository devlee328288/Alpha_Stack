def _plain_rows(rows: Sequence[Sequence[str]]) -> List[List[str]]:
    """계획서 빌더의 표를 보고서용으로 옮긴다 — 결정 기록 번호 · 줄표 · 가운뎃점 나열 · 내부 용어.

    숫자와 행 순서는 그대로 두므로 계획서와 보고서가 같은 값을 쓴다는 원칙은 지켜진다.
    "결정 기록" 행은 번호만 담고 있어 통째로 뺀다(근거 문서는 부록 B).
    """
    out: List[List[str]] = []
    for row in rows:
        if row and row[0] == "결정 기록":
            continue
        cells = []
        for cell in row:
            text = _DOC_REF.sub("", cell).replace(" — ", ": ").replace(" · ", ", ")
            for before, after in _PLAIN_TERMS:
                text = text.replace(before, after)
            cells.append(text)
        out.append(cells)
    return out

