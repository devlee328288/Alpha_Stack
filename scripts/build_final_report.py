#: w:pPr 자식의 스키마 순서. 이 순서를 어기면 Word 가 "내용에 문제가 있다" 며 복구를 제안한다.
_PPR_AFTER_AUTOSPACE = (
    "w:bidi", "w:adjustRightInd", "w:snapToGrid", "w:spacing", "w:ind", "w:contextualSpacing",
    "w:mirrorIndents", "w:suppressOverlap", "w:jc", "w:textDirection", "w:textAlignment",
    "w:textboxTightWrap", "w:outlineLvl", "w:divId", "w:cnfStyle", "w:rPr", "w:sectPr",
    "w:pPrChange",
)


def _no_autospace(p) -> None:
    """한글 · 라틴 자동 간격을 끈다 — Word 가 "2010 년" 처럼 공백을 끼워 넣지 않게.

    계획서 빌더 `_tight` 와 같은 목적이지만 원소를 **스키마 자리**에 끼운다.
    """
    pPr = p._p.get_or_add_pPr()
    dn = OxmlElement("w:autoSpaceDN")
    dn.set(qn("w:val"), "0")
    pPr.insert_element_before(dn, *_PPR_AFTER_AUTOSPACE)
    de = OxmlElement("w:autoSpaceDE")
    de.set(qn("w:val"), "0")
    pPr.insert_element_before(de, "w:autoSpaceDN")


def _outline(p, level: int) -> None:
    """문단에 개요 수준을 넣는다 — Word 목차(`TOC \\u`)와 탐색 창이 이것을 읽는다.

    ⚠️ '제목 1' 같은 스타일 이름에 기대지 않는다. 기반 docx 가 한글 Word 로 만든 것이라 스타일
       이름이 언어판마다 달라 KeyError 가 난다(계획서 빌더 `_borders` 와 같은 이유).
    """
    pPr = p._p.get_or_add_pPr()
    el = OxmlElement("w:outlineLvl")
    el.set(qn("w:val"), str(level))
    pPr.insert_element_before(el, "w:divId", "w:cnfStyle", "w:rPr", "w:sectPr", "w:pPrChange")


def _p(doc: Document, text: str = "", *, size: float = 10.5, bold: bool = False,
       color: str | None = None, align=None, before: float = 0.0, after: float = 6.0,
       line: float = 1.4, indent: float = 0.0, hanging: float = 0.0):
    p = doc.add_paragraph()
    fmt = p.paragraph_format
    fmt.space_before = Pt(before)
    fmt.space_after = Pt(after)
    fmt.line_spacing = line
    if indent:
        fmt.left_indent = Pt(indent)
    if hanging:
        fmt.first_line_indent = Pt(-hanging)
    p.alignment = align if align is not None else WD_ALIGN_PARAGRAPH.LEFT
    _no_autospace(p)
    if text:
        r = p.add_run(text)
        r.bold = bold
        r.font.size = Pt(size)
        if color:
            r.font.color.rgb = RGBColor.from_string(color)
        plan._ko(r)
    return p


def _heading(doc: Document, text: str, level: int) -> None:
    """장(0) · 절(1) · 소절(2). 장은 새 쪽에서 시작한다 — 연구과제 보고서 서식의 관례."""
    size, color, before, after = {
        0: (16.0, BRAND, 0.0, 12.0),
        1: (12.5, BRAND, 14.0, 5.0),
        2: (10.5, None, 9.0, 3.0),
    }[level]
    p = _p(doc, text, size=size, bold=True, color=color, before=before, after=after, line=1.2)
    p.paragraph_format.keep_with_next = True
    if level == 0:
        p.paragraph_format.page_break_before = True
    _outline(p, level)


def _page_break(doc: Document) -> None:
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


def _field_run(kind: str):
    r = OxmlElement("w:r")
    c = OxmlElement("w:fldChar")
    c.set(qn("w:fldCharType"), kind)
    r.append(c)
    return r


def _toc(doc: Document) -> None:
    """목차 필드. python-docx 는 쪽 번호를 계산할 수 없으므로 자리만 만들고 Word 가 채운다."""
    p = _p(doc, "목차", size=16, bold=True, color=BRAND, after=12, line=1.2)
    p = doc.add_paragraph()
    p._p.append(_field_run("begin"))
    r = OxmlElement("w:r")
    t = OxmlElement("w:instrText")
    t.set(qn("xml:space"), "preserve")
    t.text = ' TOC \\o "1-2" \\h \\z \\u '
    r.append(t)
    p._p.append(r)
    p._p.append(_field_run("separate"))
    run = p.add_run("목차가 비어 있으면 Word 에서 이 줄을 오른쪽 클릭 → 필드 업데이트(F9).")
    plan._ko(run)
    p._p.append(_field_run("end"))


def _page_numbers(doc: Document) -> None:
    """바닥글 가운데 쪽 번호. 표지에는 싣지 않는다."""
    for section in doc.sections:
        section.different_first_page_header_footer = True
        footer = section.footer
        footer.is_linked_to_previous = False
        p = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
        for child in list(p._p):
            if child.tag != qn("w:pPr"):
                p._p.remove(child)
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        fld = OxmlElement("w:fldSimple")
        fld.set(qn("w:instr"), "PAGE")
        r = OxmlElement("w:r")
        t = OxmlElement("w:t")
        t.text = "1"
        r.append(t)
        fld.append(r)
        p._p.append(fld)


def _code(doc: Document, lines: Sequence[str]) -> None:
    """명령 줄. 라틴은 Consolas, 한글 주석은 맑은 고딕으로 섞어 쓴다."""
    for i, line in enumerate(lines):
        p = _p(doc, "", after=0 if i < len(lines) - 1 else 8, line=1.15, indent=12)
        r = p.add_run(line)
        r.font.size = Pt(9)
        r.font.name = "Consolas"
        rPr = r._element.get_or_add_rPr()
        rFonts = rPr.find(qn("w:rFonts"))
        if rFonts is None:
            rFonts = rPr.makeelement(qn("w:rFonts"), {})
            rPr.append(rFonts)
        rFonts.set(qn("w:ascii"), "Consolas")
        rFonts.set(qn("w:hAnsi"), "Consolas")
        rFonts.set(qn("w:eastAsia"), plan.FONT_KO)
        r.font.color.rgb = RGBColor.from_string("333333")


