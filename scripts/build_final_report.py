def _toc_html(blocks: Sequence[Block]) -> str:
    items: List[str] = []
    open_sub = False
    n = 0
    for b in blocks:
        if b[0] == "h1":
            if open_sub:
                items.append("</ol></li>")
                open_sub = False
            elif items:
                items.append("</li>")
            n += 1
            items.append(f'<li><a href="#s{n}">{plan._h(b[1])}</a>')
        elif b[0] == "h2":
            if not open_sub:
                items.append("<ol>")
                open_sub = True
            n += 1
            items.append(f'<li><a href="#s{n}">{plan._h(b[1])}</a></li>')
    items.append("</ol></li>" if open_sub else "</li>")
    return '<nav class="toc"><b>목차</b><ol>' + "".join(items) + "</ol></nav>"


def render_html(blocks: Sequence[Block], out: Path) -> str:
    """docx 와 같은 내용을 HTML 한 장으로. 그림은 PNG 를 상대 경로로 가리킨다."""
    parts: List[str] = [
        '<header class="cover">'
        '<p class="eyebrow">QURIOUS · 1차 프로젝트</p>'
        f"<h1>{plan._h(TITLE)}</h1>"
        f'<p class="sub">{plan._h(SUBTITLE)}</p>'
        f'<p class="thesis">{plan._h(plan.PROJECT_NAME[0])}</p>'
        '<p class="meta">' + "<br>".join(plan._h(m) for m in COVER_META)
        + f"<br>생성 {datetime.now(plan.KST):%Y-%m-%d %H:%M} KST · 정본 "
        "<code>scripts/build_final_report.py</code> · docx 와 같은 내용</p>"
        "</header>"
    ]
    n = 0
    for b in blocks:
        kind = b[0]
        if kind == "toc":
            parts.append(_toc_html(blocks))
        elif kind == "h1":
            n += 1
            parts.append(f'<h1 class="ch" id="s{n}">{plan._h(b[1])}</h1>')
        elif kind == "h2":
            n += 1
            parts.append(f'<h2 id="s{n}">{plan._h(b[1])}</h2>')
        elif kind == "h3":
            parts.append(f"<h3>{plan._h(b[1])}</h3>")
        elif kind == "p":
            parts.append(f"<p>{plan._h(b[1])}</p>")
        elif kind == "small":
            parts.append(f'<p class="small">{plan._h(b[1])}</p>')
        elif kind == "bullets":
            parts.append('<ul class="bul">'
                         + "".join(f"<li>{plan._h(x)}</li>" for x in b[1]) + "</ul>")
        elif kind == "quote":
            parts.append(f"<blockquote><p>“{plan._h(b[1])}”</p>"
                         f"<cite>— {plan._h(b[2])}</cite></blockquote>")
        elif kind == "code":
            parts.append("<pre>" + html.escape("\n".join(b[1])) + "</pre>")
        elif kind == "table":
            if b[4]:
                parts.append(f'<p class="cap">{plan._h(b[4])}</p>')
            parts.append('<div class="tablewrap">' + plan._html_table(b[1], b[3]) + "</div>")
        elif kind == "figure":
            path: Path = b[1]
            rel = os.path.relpath(path, out.parent).replace(os.sep, "/")
            if path.exists():
                parts.append(f'<figure><img src="{rel}" alt="{plan._h(b[2])}">'
                             f"<figcaption>{plan._h(b[2])}</figcaption></figure>")
            else:
                parts.append(f"<figure><figcaption>{plan._h(b[2])} — 그림 없음 ({rel})"
                             "</figcaption></figure>")
    return HTML_HEAD.replace("{title}", plan._h(TITLE + " — Qurious 1차")) \
        + "\n".join(parts) + HTML_TAIL


# ── Word 마무리 — 목차 · 쪽 번호 필드 갱신 ─────────────────────────────────

def finalize_with_word(path: Path, pdf: Path | None) -> int | None:
    """Word 로 필드를 채우고 저장한다. 쪽수를 돌려준다.

    python-docx 는 쪽을 나눌 수 없어 목차의 쪽 번호를 모른다. 쪽을 아는 것은 Word 뿐이다.
    ⚠️ 없으면 예외 대신 **무엇을 하면 되는지** 출력하고 None — docx 는 이미 저장돼 있다.
    """
    try:
        import win32com.client  # noqa: PLC0415 — Windows 에서만 필요한 선택 의존성
    except ImportError:
        print("   ⚠️ pywin32 가 없어 목차를 채우지 못했습니다.")
        print("      할 일: pip install pywin32 · 또는 Word 에서 열어 목차를 오른쪽 클릭 → 필드 "
              "업데이트")
        return None
    word = win32com.client.DispatchEx("Word.Application")
    word.Visible = False
    word.DisplayAlerts = 0
    try:
        doc = word.Documents.Open(str(path.resolve()))
        # 목차가 늘어나면 뒤 쪽 번호가 밀리므로 두 번 갱신한다
        for _ in range(2):
            doc.Fields.Update()
            for i in range(1, doc.TablesOfContents.Count + 1):
                doc.TablesOfContents(i).Update()
        pages = int(doc.ComputeStatistics(2))  # 2 = wdStatisticPages
        doc.Save()
        if pdf is not None:
            pdf.parent.mkdir(parents=True, exist_ok=True)
            doc.ExportAsFixedFormat(str(pdf.resolve()), 17)  # 17 = wdExportFormatPDF
        doc.Close(False)
        return pages
    finally:
        word.Quit()


